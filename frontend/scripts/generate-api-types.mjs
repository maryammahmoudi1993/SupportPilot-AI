#!/usr/bin/env node
/**
 * Regenerates frontend/src/types/api.ts from the backend's live OpenAPI
 * schema (drf-spectacular). This is the single source of truth for the
 * frontend/backend API contract — never hand-edit the generated output.
 *
 * Steps:
 *   1. Run the Django `spectacular` management command against the local
 *      backend virtualenv to produce frontend/openapi.yaml.
 *   2. Run openapi-typescript against that file to produce
 *      frontend/src/types/api.ts.
 *
 * Requires a backend virtualenv at backend/venv (see backend/README or
 * repository setup docs). No network calls and no running server are
 * required — the schema is built by importing the Django app config.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const frontendRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repoRoot = path.dirname(frontendRoot);
const backendRoot = path.join(repoRoot, "backend");
const schemaPath = path.join(frontendRoot, "openapi.yaml");
const typesPath = path.join(frontendRoot, "src", "types", "api.ts");

const pythonBin =
  process.platform === "win32"
    ? path.join(backendRoot, "venv", "Scripts", "python.exe")
    : path.join(backendRoot, "venv", "bin", "python");

if (!existsSync(pythonBin)) {
  console.error(
    `Backend virtualenv not found at ${pythonBin}.\n` +
      "Create it first (see backend/README) before regenerating API types.",
  );
  process.exit(1);
}

const schemaEnv = {
  ...process.env,
  // Minimal settings needed to import the Django app config and build the
  // schema. None of these are used to run a server or touch a real
  // database/redis connection.
  DEBUG: process.env.DEBUG ?? "True",
  SECRET_KEY: process.env.SECRET_KEY ?? "schema-generation-only",
  ALLOWED_HOSTS: process.env.ALLOWED_HOSTS ?? "localhost,127.0.0.1",
  DATABASE_URL: process.env.DATABASE_URL ?? "sqlite:///./schema_generation.sqlite3",
  REDIS_URL: process.env.REDIS_URL ?? "redis://localhost:6379/0",
};

console.log("[1/2] Generating OpenAPI schema from backend (drf-spectacular)...");
const schemaResult = spawnSync(
  pythonBin,
  ["manage.py", "spectacular", "--file", schemaPath, "--fail-on-warn"],
  { cwd: backendRoot, env: schemaEnv, stdio: "inherit" },
);

// Clean up the throwaway sqlite file created only to satisfy Django's
// database check during schema generation.
const tmpDb = path.join(backendRoot, "schema_generation.sqlite3");
if (existsSync(tmpDb)) {
  await import("node:fs").then((fs) => fs.promises.rm(tmpDb, { force: true }));
}

if (schemaResult.status !== 0) {
  console.error("OpenAPI schema generation failed.");
  process.exit(schemaResult.status ?? 1);
}

console.log("[2/2] Generating TypeScript types (openapi-typescript)...");
// Called as a library (not the CLI via npx) so paths containing spaces
// resolve correctly on Windows, where an extra shell layer mis-splits them.
const schemaText = readFileSync(schemaPath, "utf-8");
const ast = await openapiTS(schemaText, { cwd: frontendRoot });
const header =
  "/**\n" +
  " * This file was auto-generated by openapi-typescript.\n" +
  " * Do not make direct changes to the file.\n" +
  " */\n\n";
writeFileSync(typesPath, header + astToString(ast));

console.log(`\nDone. Regenerated:\n  ${schemaPath}\n  ${typesPath}`);
